HOUSTON, April 17, 2003 -- Rice University chemists hope a new variant of vancomycin that contains buckyballs -- tiny cage-shaped molecules of pure carbon -- could become the world's first targeted antibiotic, creating a new line of defense against bioweapons like anthrax.<BR>
<BR>
Vancomycin, which entered clinical service 40 years ago, is the antibiotic of last resort, given only when all others fail. Unfortunately, vancomycin-resistant strains of bacteria have appeared in recent years. <BR>
<BR>
In an effort to reinvigorate vancomycin, researchers have created vancomycin conjugates -- pairs of vancomycin molecules joined by an intermediate molecule that acts as a bridge -- some of which have proven more effective at killing resistant bacteria. <BR>
<BR>
Rice Chemistry Professor Lon Wilson decided to create a buckyball-vancomycin conjugate following years of work developing biochemical targeting mechanisms for buckyballs, spherical cages containing 60 carbon molecules. By linking antibodies to a buckyball with anticancer drugs attached to it, Wilson and two of his graduate students, Tatiana Zakharian and Jared Ashcroft, are creating targeted compounds that will bind only with certain cells, like those found in melanoma tumors, for example. <BR>
<BR>
"Having the ability to target antibiotics to attack specific bacterial antigens opens the door for treatments that simply aren't available today," said Wilson. "For example, we believe it's feasible to create a C60-vancomycin conjugate that attaches to anthrax while it is still in the spore form." <BR>
<BR>
Weaponized anthrax is delivered in spores, a dormant form in which the disease is encased in a rugged shell. Once the spore finds its way into a living host, it germinates and becomes active. <BR>
<BR>
Wilson said vancomycin can attack anthrax only after it germinates. However, having the ability to affix the antibiotic to a spore could enable the drug to knock the disease out when it tries to emerge from hibernation, before it has a chance to spread throughout the body and release its toxins. <BR>
<BR>
A postdoctoral fellow in Wilson's lab, Dr. Andrey Mirakyan, recently presented preliminary results of the work at this spring's American Chemical Society annual meeting and they expect to publish research findings soon.
