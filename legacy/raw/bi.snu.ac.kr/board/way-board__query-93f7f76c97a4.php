<BR>
1. 한국데이터베이스진흥센터나 정보통신부에서 추진하는 데이터베이스 관련 제반사업에 대한 심사 및 자문위원으로 위촉<BR>
<BR>
2. 한국데이터베이스진흥센터의 온라인 서비스 '국내외 DB 및 IT 뉴스레터'제공<BR>
<BR>
라. 등록방법 : 센터 홈페이지를 통한 온라인 등록<BR>
