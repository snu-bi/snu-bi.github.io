1st International Workshop on Biological Data Management (BIDM'03) <BR>
(In conjunction with DEXA 2003, Prague, Czech Republic)<BR>
<BR>
URL: <A HREF="http://www.ntu.edu.sg/home/assourav/bidm.htm" TARGET=_blank>http://www.ntu.edu.sg/home/assourav/bidm.htm</A><BR>
URL: <A HREF="http://www.dexa.org" TARGET=_blank>www.dexa.org</A><BR>
<BR>
Technological advances in high throughput screening coupled with the genomic <BR>
revolution resulted in a large amount of life science data. This data, which<BR>
&nbsp;lies at the foundation of hypothesis development and experiment validation, <BR>
is often stored in geographically distributed databases. These databases contain<BR>
&nbsp;annotated genomic sequence information, or the results of new high-throughput <BR>
techniques such as microarray experiments, or curated databases containing <BR>
carefully scrutinized existing research, systematically compiled by domain <BR>
experts. It is useful to correlate these databases with those containing medical <BR>
records, information on disease, databases on references to literature, databases <BR>
containing information on the properties of chemicals and their molecular <BR>
structure. These databases hold information that is critical to biomedical and <BR>
life science researchers. Hence, the problem of integrating, querying and mining <BR>
heterogenous bioinformatics resources is of immense importance. Useful queries do <BR>
span through a multitude of databases in the categories mentioned above.<BR>
<BR>
However, integrating, querying and mining biological data from disparate sources <BR>
is a challenging problem due to the nature of biological data. Most data<BR>
pertaining to genomics and molecular biology is characterized by being highly evolving <BR>
and semi-structured. Moreover, genomic data available from public and private <BR>
repositories is voluminous, highly heterogeneous, and not consistently represented. The <BR>
heterogeneity results from our evolving understanding of complex biological systems; <BR>
the numerous disparities in modeling biological systems across organisms, across tissue, <BR>
in different environments and over time; and disparities across the scientific community <BR>
in their understanding of these systems. Moreover, there continues to be a lack of common <BR>
standards in the representation of biological data. In fact, the extremely rapid pace <BR>
of change of the field - in terms of science, technology, and business - discourages the <BR>
development of stable standards for interoperation and formation of commercial companies that can deliver specialized software of reasonable prices. This results in crippling incompatibilities among software tools and databases. Scientists find it slow, cumbersome, and labor-intensive to establish connections across information resources that fuel scientific research. Addressing this challenge will facilitate the way life science data is accessed, retrieved, analyzed and combined with other data.<BR>
This workshop is intended to bring together researchers in the management of biological&nbsp; <BR>
data. We solicit papers with important new insights and experiences on managing <BR>
biological data. Topics of interest lie at the intersection of data management <BR>
and bioinformatics. They include, but are not limited to&nbsp; <BR>
<BR>
-Database integration and interoperability <BR>
-Warehousing biological data <BR>
-Information Modeling, metadata and data sharing <BR>
-Multidatabase indexing and multidatabase queries <BR>
-Data semantic and control <BR>
-Ontology design <BR>
-Biological Workflows<BR>
-Knowledge discovery and data mining <BR>
-Algorithms for large scale and distributed biological databases <BR>
-Protein structure prediction <BR>
-Modeling of Biochemical Pathways <BR>
-Recognition of Genes and Regulatory Elements <BR>
-Molecular Sequence analysis <BR>
-Genome comparative analysis <BR>
<BR>
PAPER SUBMISSION: <BR>
<BR>
The full paper submissions should not be more than 5 pages (Two columns IEEE format) <BR>
in length. Please submit the PDF version of your manuscript to <A HREF="mailto:assourav@ntu.edu.sg.">assourav@ntu.edu.sg.</A> <BR>
Papers will be reviewed by at least 3 program committee members for their technical merit, <BR>
originality, significance, and relevance to the workshop. Accepted papers will be <BR>
published by IEEE Computer Society Press in the Proceedings of the DEXA'2003 Workshops. <BR>
Please send abstract (no more than 250 words in ASCII text) of the paper via email <BR>
including title of the paper, authors' name, and 3-4 keywords. <BR>
<BR>
Extended versions of selected accepted papers will be considered for publication in a <BR>
special issue of Data and Knowledge Engineering (DKE) journal (Elsevier Science). <BR>
