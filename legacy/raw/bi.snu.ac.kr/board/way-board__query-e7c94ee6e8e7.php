<BR>
○ 16 일 일 주 제 시 간 내 용 <BR>
1일 패러다임 전환 및기업 생태계의 이해 13:30 <BR>
~ <BR>
14:30 1. 패러다임 전환 <BR>
- 고객과 제품/서비스의 가치 <BR>
2. 기업 생태계의 이해 <BR>
- Information Engineering의 성장 <BR>
- Enterprise Engineering의 탄생 <BR>
- BPR과 Business Engineering <BR>
- ERP와 Resource Engineering <BR>
- TQM과 Human Engineering <BR>
기업 데이터/정보 품질의 정의 14:30 <BR>
~ <BR>
15:30 3. 기업 데이터/정보/지식의 본질성 <BR>
- 지식계층도 <BR>
- 3Ps(Project, Process, Product) <BR>
- 데이터/정보/지식의 정의 <BR>
