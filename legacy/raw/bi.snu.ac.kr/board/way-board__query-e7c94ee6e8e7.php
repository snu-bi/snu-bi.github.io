▶ 데이터 품질관리 <BR>
<BR>
■ 목적 및 소개 <BR>
<BR>
<BR>
○기업의 비즈니스 성패를 다루는 품질 좋은 데이터는 기업의 자산이며 생존을 위한 기반으로 비즈니스의 주요영향요소(Critical Success Factor)이다. <BR>
품질 좋은 데이터 확보를 위한 방안은 무엇일까? 선진사례와 기업생태계를 이해함으로써 품질 확보에 대한 전략방안 및 핵심프로세스의 최적의 지름길을 알아보자. <BR>
○ 정부와 기업의 정보화 담당자와의 Data Information Quality 대한정보 교류의 장 마련. <BR>
<BR>
■ 개요 <BR>
<BR>
○ 워크숍명 : Enterprise Data Information Quality <BR>
○ 일 시 : 2003년 5월 23일(금), 13:30- 17:30 <BR>
○ 장 소 : 한국관광공사지하1층 세미나실 <BR>
○ 주 최 : 한국데이터베이스진흥센터,기업지식전략컨설팅(유) <BR>
○ 후 원 : 전자신문사, (주)아이티월드온라인, (주)코리아인터넷닷컴, (주)데브피아, (주)잇이즈콤, (주)날리지매트릭스, DB설계 튜닝(프리첼커뮤니티), 데이터품질관리포럼(IT Warehouse) <BR>
<BR>
<BR>
■ 참가대상 <BR>
<BR>
○ 각 정부부처 정보화 담당관, 학술단체 및 연구기관,정보담당임원(CIO), 정보관리자(Information <BR>
Administrator), 정보전략기획자, 정보모델러, 데이터관리자, 데이터베이스관리자,프로세스관리자, 리파지토리관리자, 엔터프라이즈(비즈니스/자원/인간공학 엔지니어) <BR>
○ 참석인원 : 100명 <BR>
<BR>
<BR>
■ 참가비용 <BR>
<BR>
○ 참 가 비 : 사전등록 50,000원 / 현장등록 70,000원 (자료집 포함) <BR>
* 사전등록은 <A HREF="http://www.dpc.or.kr" TARGET=_blank>www.dpc.or.kr</A> 사이트를 통하여 워크숍 5일 전까지 수강신청 접수 및 입금 완료한 사람에 한함 <BR>
<BR>
<BR>
<BR>
