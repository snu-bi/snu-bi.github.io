4/18/2003 -- Scientists from Northwestern University and Argonne National Laboratory have created a hybrid “nanodevice” composed of a “scaffolding” of titanium oxide nanocrystals attached with snippets of DNA that may one day be used to target defective genes that play a role in cancer, neurological disease and other conditions. <BR>
<BR>
<BR>
The titanium oxide nanocrystals, which are less than a few billionths of a meter in diameter and are the same material used in artificial hips and knees, may provide the ideal means of overcoming current limitations of gene therapy, such as adverse reactions to genetically modified viruses used as vehicles to deliver genes into cells, according to researchers Tatjana Paunesku and Gayle Woloschak of Northwestern University. <BR>
<BR>
<BR>
Paunesku is research assistant professor of radiology, and Woloschak is professor of radiology at the Feinberg School of Medicine at Northwestern University. They are both researchers at The Robert H. Lurie Comprehensive Cancer Center of Northwestern University and at Argonne National Laboratory.<BR>
<BR>
<BR>
In experiments described in the May online version of Nature Materials, the research team showed that nanocomposites not only retain the individual physical and biological activity of titanium oxide and of DNA, but, importantly, also possess the unique property of separating when exposed to light or x-rays.<BR>
<BR>
<BR>
For example, researchers would attach to the titanium oxide scaffolding a strand of DNA that matches a defective gene within a cell and introduce the nanoparticle into the nucleus of the cell, where the DNA would bind with its “evil twin” DNA strand to form a double-helix molecule. <BR>
<BR>
The scientists would then expose the nanoparticle to light or x-rays, which would snip off the defective gene. <BR>
<BR>
“We call it a ‘Swiss army knife’ because, unlike today’s drugs, we can inject 10 kinds of good genes all at once and target them in extremely specific or extremely broad ways,” Paunesku said.<BR>
<BR>
<BR>
The titanium oxide “scaffolding” also is amenable to attaching other molecules, for example, navigational peptides, or proteins, which, like viral vectors, can help the nanoparticles home in on the cell nucleus. <BR>
<BR>
The research group’s work is still in the early stages of development, and testing in a laboratory model is at least two years away, Woloschak said.<BR>
<BR>
<BR>
Also working on this project were Natasa Stojicevic, of the Feinberg School, and Tijana Rajh, Marion Thurnauer, Jorg Maser, Stefan Vogt, Gary Wiederrect, Miroslava Protic, Barry Lai and Jeremy Oryhon of Argonne National Laboratory.<BR>
<BR>
This study was supported by grants from the National Institutes of Health and from the U.S. Department of Energy.<BR>
