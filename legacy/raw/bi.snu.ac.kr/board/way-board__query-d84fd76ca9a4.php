<BR>
20. 허리 무릎이 아프고 저리며 또한 위장장애 증세, 내장기능 약화와 같은 증세가 현재 사는 집으로 이사와서 생겼다. <BR>
<BR>
21. 가슴이 답답하고 두근거리며 늘 기운이 없거나 어깨, 등줄기, 팔 등이 쑤시는 증세가 지속적으로 계속된다고 자주 느낀 적이 있다. <BR>
<BR>
22. 병이 있다면 그 병이 현재의 집으로 옮긴 때부터 생겼다. 21. 집안의 어느 장소에서는 부자연스럽게 오싹 하거나 음습한 기분이 드는 장소가 있다. <BR>
<BR>
23. 가족 중 집안 분위기가 편안하지 못하다고 느끼는 사람이 있다. <BR>
<BR>
24. 귀신을 보거나 환청, 가위눌림 등의 경험이 있다. <BR>
<BR>
25. 집에 있으면 짜증이 나거나 기분이 좋지 않은데 집을 떠나면 기분이 좋아진다. <BR>
<BR>
26. 침대 위나 아래 혹은 주로 자신이 잠자는 곳에서 고양이가 놀기 좋아 한다. <BR>
