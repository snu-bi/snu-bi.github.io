<BR>
3. 자신이 살고 있는 아파트의 같은 통로에 사는 아래층이나 위층의 사람들이 자주 아파서 병원 신세를 지거나 중풍으로 고생하는 사람이 많이 발생한다. <BR>
<BR>
4. 건물 외부에 부착한 타일이나 석재가 자주 떨어진다. <BR>
<BR>
5. 건물 내부는 벽지를 발라서 잘 구분이 되지 않으나 외부에는 건물의 벽에 금이 가 있는 곳이 있다. <BR>
<BR>
6. 가끔 조용한 밤에 약하게 삐꺽거리는 소리가 들린 적이 있다. <BR>
<BR>
7. 숙면을 취하기가 힘들고 꿈을 많이 꾸거나 비슷한 꿈이 며칠째 계속된 적이 있다. <BR>
<BR>
8. 아침에 일어나면 잠을 잔 것 같지 않고 계속 졸린다. <BR>
<BR>
9. 회사에 출근해서도 오전에는 피곤이 잘 풀리지 않고 오후가 되어서야 컨디션 조절이 되는 경우가 많이 있다. <BR>
<BR>
10. 예전에 살던 곳에서 지금 사는 집으로 이사온 후 그렇게 무리하지도 않았는데 이유 없이 아픈 데가 자주 생긴다. <BR>
<BR>
11. 자녀들이 자주 아프거나 잠을 잘 때도 심하게 몸부림을 쳐서 처음 누였던 자리에서 이동하여 항상 다른 자리에 잠들고 있다. <BR>
<BR>
12. 회사에서 퇴근해서 바로 집에 가기 싫어서 일부러 술자리를 만들어 늦게 들어가고 싶은 적이 많다. <BR>
<BR>
13. 자녀의 경우, 자신의 방에서 공부하기 싫어하고 책상에 앉기 싫어한다. <BR>
<BR>
14. 화장실 내부의 타일에 금이 가거나 타일이 떨어진 적이 있다. <BR>
<BR>
15. 나이가 드신 분의 경우 이유 없이 손발이 저리거나 뻐근함을 느낀 적이 자주 있다. <BR>
<BR>
16. 지금 사는 집으로 이사오고 난 뒤에 가족 중에서 중풍에 걸린 분이 있다. <BR>
<BR>
17. 집안에 개미나 바퀴벌레가 유난히 많이 있다. <BR>
<BR>
18. 문짝이 뒤틀리거나 출입문이 꽉 닫히지 않는 문이 있다. <BR>
