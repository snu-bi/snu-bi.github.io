Call for Papers and Proposals<BR>
<BR>
The Seventh Pacific-Asia Conference on Knowledge <BR>
Discovery and Data Mining (PAKDD03)<BR>
<BR>
The Convention and Exhibition Center (COEX), Seoul, Korea<BR>
April 30 &#8211; May 2, 2003<BR>
<A HREF="http://aitrc.kaist.ac.kr/~pakdd03" TARGET=_blank>http://aitrc.kaist.ac.kr/~pakdd03</A><BR>
<BR>
The Seventh Pacific-Asia Conference on Knowledge Discovery and Data Mining (PAKDD-03) aims to provide a forum for academic researchers and industry practitioners to share original research results and development experiences from different KDD related areas such as data mining, data warehousing, machine learning, databases, statistics, knowledge acquisition and discovery, data visualization, and knowledge-based systems. The conference solicits research papers as well as proposals for tutorials and workshops on all aspects of knowledge discovery and data mining. <BR>
<BR>
Areas of Interests (including, but not limited to) <BR>
&nbsp;<BR>
<BR>
* Data Mining Biomedical Domains<BR>
* Novel Data Mining algorithms<BR>
* Data and Knowledge Representation<BR>
* Scientific Discovery<BR>
* Machine Learning Methods<BR>
* Statistical Methods<BR>
* Mining High Dimensional Data<BR>
* Text Data Mining<BR>
* Temporal Data Mining<BR>
* Data and Knowledge Visualization<BR>
* Interactive and Online Mining<BR>
* KDD Process and Human Interaction<BR>
* Data Mining in Advanced (OO, Spatial, Multimedia) Databases<BR>
* Integration of Data Warehousing, OLAP and Data Mining<BR>
* Parallel and Distributed Data Mining<BR>
* Data Mining and the Internet<BR>
* Multi-agent, Multi-task KDD Systems<BR>
* Data Mining from Unstructured and Multimedia Data<BR>
* Security and Privacy Issues<BR>
